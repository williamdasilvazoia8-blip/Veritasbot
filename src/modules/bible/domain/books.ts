/**
 * Catálogo canônico dos 73 livros da Bíblia católica.
 *
 * - `id`: identificador estável (estilo OSIS/USFM), independente de edição.
 * - `aliases`: formas aceitas pelo parser, já em minúsculas e SEM acentos.
 *   Para livros numerados, os aliases são a base ("joao" em "1 João").
 * - `ambiguousLowercase`: aliases que também são palavras comuns em português
 *   (ex.: "os", "na", "mal"). Na detecção automática só valem com inicial maiúscula.
 * - `matosSoares`: nome do livro no arquivo de origem e número de capítulos esperado.
 */

