export const BOOKS: readonly BookDefinition[] = DEFS.map((d, i) => ({ ...d, order: i + 1 }));

const BY_ID = new Map(BOOKS.map((b) => [b.id, b]));

export function getBook(id: string): BookDefinition | undefined {
  return BY_ID.get(id);
}

export function requireBook(id: string): BookDefinition {
  const book = BY_ID.get(id);
  if (!book) throw new Error(`Livro desconhecido: ${id}`);
  return book;
}
